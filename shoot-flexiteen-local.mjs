import puppeteer from 'puppeteer';
import path from 'path'; import fs from 'fs'; import { fileURLToPath } from 'url';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(__dirname, 'project-previews', 'flexiteen.jpg');
const fileUrl = 'file://' + path.join(__dirname, 'flexiteen', 'index.html');
const browser = await puppeteer.launch({ headless: true });
const page = await browser.newPage();
await page.setViewport({ width: 1280, height: 720, deviceScaleFactor: 1 });
await page.goto(fileUrl, { waitUntil: 'networkidle2', timeout: 30000 });
await new Promise(r => setTimeout(r, 2500));
await page.screenshot({ path: out, type: 'jpeg', quality: 82, clip: {x:0,y:0,width:1280,height:720} });
console.log('-> ' + (fs.statSync(out).size/1024).toFixed(1) + 'KB');
await browser.close();
